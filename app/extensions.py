"""Flask extension instances, created here and bound to the app in create_app()."""
import os

from flask_migrate import Migrate
from flask_sqlalchemy import SQLAlchemy
from flask_wtf.csrf import CSRFProtect
from sqlalchemy import MetaData

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), os.pardir))

# Explicit constraint names keep migrations reproducible and let SQLite
# alter constraints through batch operations.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "%(constraint_name)s",  # the models already give check constraints full names
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

db = SQLAlchemy(metadata=MetaData(naming_convention=NAMING_CONVENTION))
# render_as_batch makes autogenerated migrations work on SQLite as well.
migrate = Migrate(directory=os.path.join(PROJECT_ROOT, "migrations"), render_as_batch=True)
csrf = CSRFProtect()
